interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const savedLanguage = localStorage.getItem("mkulima_language");
    return languageOptions.find((option) => option.value === savedLanguage)?.value ?? "en";
  });

  const setLanguage = (nextLanguage: Language) => {
    localStorage.setItem("mkulima_language", nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    const htmlLanguageCodes: Record<Language, string> = {
      en: "en",
      sw: "sw",
      gikuyu: "ki",
      dholuo: "luo",
      kalenjin: "kln",
      kikamba: "kam",
      luhya: "luy",
      kisii: "guz",
      somali: "so",
    };
    document.documentElement.lang = htmlLanguageCodes[language];
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (text) =>
        language === "sw"
          ? swahili[text] ?? text
          : language === "en"
            ? text
            : localTranslations[language]?.[text] ?? text,
    }),
    [language],
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useTranslation(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useTranslation must be used within LanguageProvider");
  }
  return context;
}
